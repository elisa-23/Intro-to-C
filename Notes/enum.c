#include <stdio.h>

enum Day
{
    SUNDAY, // 0
    MONDAY, // 1
    TUESDAY // 2
};

// enum is a user-defined data type that consists of a set of named integer constants. It is used to assign names to integral constants, which makes the code more readable and maintainable. In this example, we have defined an enum called Day that represents the days of the week. The values of the enum constants start from 0 by default, but you can also assign specific values to them if needed.
// What are the benefits of using enums in C programming? - By using Hexadecimal values, the memory usage can be reduced (will only use up a byte of memory rather than more bytes for strings)
